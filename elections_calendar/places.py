"""Place resolution (spec §6.2): raw source country text -> place.

``data/places.yaml`` is generated by ``scripts/build_places.py``. Names match
on ``text.norm_name`` (case, accents, punctuation, a leading/trailing "the").

A name that is not registered still gets a deterministic place with
``registered=False``, and the adapter marks the unit partial with reason
``place_unregistered`` (spec §9.2). Its ID is ``unknown:<key>``, where
``key`` is the normalised name with spaces as hyphens, so two unregistered
names match only when their normalised names are identical. "<Name> (part
of <Parent>)" is the registered subdivision when <Name> is one of the
parent's, however the parent is spelled; otherwise it gets
``unknown:<key>@<parent ID>``, whether or not the parent is registered.
Registered IDs never start with ``unknown:``.
"""

import re
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml

from elections_calendar.text import collapse_ws, norm_name

DEFAULT_PLACES = Path(__file__).resolve().parent.parent / "data" / "places.yaml"
UNKNOWN = "unknown:"
_PART_OF = re.compile(r"^(?P<name>.+?)\s*\(part of (?P<parent>.+)\)$", re.IGNORECASE)


@dataclass(frozen=True, slots=True)
class Place:
    place_id: str
    display: str
    country_code: str | None
    parent: str | None
    registered: bool = True


class PlaceRegistry:
    def __init__(self, places: dict[str, Place], aliases: dict[str, str]) -> None:
        self._places = places
        self._aliases = aliases

    @classmethod
    def load(cls, path: Path = DEFAULT_PLACES) -> PlaceRegistry:
        raw: dict[str, dict[str, Any]] = yaml.safe_load(path.read_text(encoding="utf-8"))
        places: dict[str, Place] = {}
        aliases: dict[str, str] = {}
        for place_id, entry in raw.items():
            if place_id.startswith(UNKNOWN):
                raise ValueError(f"{place_id}: {UNKNOWN} is reserved for unregistered names")
            places[place_id] = Place(
                place_id, entry["display"], entry["country_code"], entry["parent"]
            )
            for alias in entry["aliases"]:
                owner = aliases.setdefault(norm_name(alias), place_id)
                if owner != place_id:
                    raise ValueError(f"alias {alias!r} names both {owner} and {place_id}")
        return cls(places, aliases)

    def get(self, place_id: str) -> Place:
        return self._places[place_id]

    def __contains__(self, place_id: object) -> bool:
        return place_id in self._places

    def resolve(self, raw: str) -> Place | None:
        """The place for a source's country text; None when the text is empty."""
        text = collapse_ws(raw)
        key = norm_name(text)
        if not key:
            return None
        place_id = self._aliases.get(key)
        if place_id is not None:
            return self._places[place_id]
        part_of = _PART_OF.match(text)
        if part_of:
            parent = self.resolve(part_of["parent"])
            name = norm_name(part_of["name"])
            if parent is not None and name:
                known = self.resolve_subdivision(parent.place_id, part_of["name"])
                if known is not None:
                    return known
                place_id = f"{UNKNOWN}{_id_key(name)}@{parent.place_id}"
                return Place(place_id, text, None, parent.place_id, False)
        return Place(f"{UNKNOWN}{_id_key(key)}", text, None, None, False)

    def resolve_subdivision(self, parent_id: str, name: str) -> Place | None:
        """A registered subdivision of ``parent_id`` called ``name`` (UK + Scotland -> GB-SCT)."""
        place_id = self._aliases.get(norm_name(name))
        if place_id is None or self._places[place_id].parent != parent_id:
            return None
        return self._places[place_id]


def _id_key(key: str) -> str:
    """A normalised name as an ID fragment; one-to-one, apostrophes kept."""
    return key.replace(" ", "-")


DEFAULT_SUBDIVISIONS = Path(__file__).resolve().parent.parent / "data" / "subdivisions.yaml"
_SUBDIVISION_SUFFIXES = (" prefecture", " state", " province", " region")


class SubdivisionIndex:
    """First-level subdivisions (ISO 3166-2) by country and normalised name.

    ``data/subdivisions.yaml`` is generated by ``scripts/build_subdivisions.py``.
    """

    def __init__(self, index: dict[str, dict[str, str]]) -> None:
        self._index = index

    @classmethod
    def load(cls, path: Path = DEFAULT_SUBDIVISIONS) -> SubdivisionIndex:
        raw: dict[str, dict[str, str]] = yaml.safe_load(path.read_text(encoding="utf-8"))
        return cls(raw)

    def find(self, country_code: str | None, name: str) -> str | None:
        """The ISO 3166-2 code of ``name`` in the country; None when unknown or ambiguous."""
        if not country_code or not name:
            return None
        keys = self._index.get(country_code)
        key = norm_name(name)
        if keys is None or not key:
            return None
        if key in keys:
            return keys[key]
        for suffix in _SUBDIVISION_SUFFIXES:
            if key.endswith(suffix) and key[: -len(suffix)] in keys:
                return keys[key[: -len(suffix)]]
        return None


_LABEL_WORD = re.compile(r"[^\W\d_]+(?:[-'’][^\W\d_]+)*")
_MAX_RUN = 5


def named_subdivisions(
    text: str, place: Place, places: PlaceRegistry, subdivisions: SubdivisionIndex
) -> tuple[str, ...]:
    """The registered subdivisions of ``place`` that a label names, in text order.

    Runs of up to five words that name the place itself are taken first and never count
    ("Mexico", "Trinidad and Tobago"); then the longest runs that resolve to a subdivision.
    One run per subdivision code.
    """
    words = _LABEL_WORD.findall(text)
    taken = [False] * len(words)
    found: dict[str, tuple[int, str]] = {}
    for own_name in (True, False):
        for n in range(min(_MAX_RUN, len(words)), 0, -1):
            for i in range(len(words) - n + 1):
                if any(taken[i : i + n]):
                    continue
                run = " ".join(words[i : i + n])
                if own_name:
                    same = places.resolve(run)
                    hit = same is not None and same.place_id == place.place_id
                else:
                    code = subdivisions.find(place.country_code, run)
                    hit = code is not None
                    if code is not None:
                        found.setdefault(code, (i, run))
                if hit:
                    taken[i : i + n] = [True] * n
    return tuple(run for _, run in sorted(found.values()))


def named_places(text: str, places: PlaceRegistry) -> list[tuple[str, Place]]:
    """The registered places a text names, in text order, as (words, place).

    Runs of up to five words are tried longest first, leftmost first within a length; a run
    is taken when none of its words is taken yet and it resolves to a registered place, so
    "Republic of the Congo" wins over "Congo". Only the first run per place ID is kept, and a
    place that is the parent of another kept place is dropped (the child refines it:
    "United Kingdom Scotland" gives Scotland). Unregistered places are never returned.
    """
    words = _LABEL_WORD.findall(text)
    taken = [False] * len(words)
    found: dict[str, tuple[int, str, Place]] = {}
    for n in range(min(_MAX_RUN, len(words)), 0, -1):
        for i in range(len(words) - n + 1):
            if any(taken[i : i + n]):
                continue
            run = " ".join(words[i : i + n])
            place = places.resolve(run)
            if place is not None and place.registered:
                taken[i : i + n] = [True] * n
                found.setdefault(place.place_id, (i, run, place))
    parents = {place.parent for _, _, place in found.values() if place.parent}
    kept = [v for v in found.values() if v[2].place_id not in parents]
    return [(run, place) for _, run, place in sorted(kept, key=lambda v: v[0])]
