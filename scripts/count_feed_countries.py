"""Count the country strings in every published elections.json in git history.

Writes data/feed_country_history.tsv, the frozen display-name evidence used
by scripts/build_places.py (spec §6.2). Read-only on the repository.

    .venv\\Scripts\\python.exe -m scripts.count_feed_countries ff30417
"""

import argparse
import collections
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "data" / "feed_country_history.tsv"


def git(*args: str) -> bytes:
    return subprocess.run(["git", *args], cwd=ROOT, check=True, capture_output=True).stdout


def count(ref: str) -> tuple[collections.Counter[str], int]:
    commits = git("log", "--format=%H", ref, "--", "elections.json").decode().split()
    counts: collections.Counter[str] = collections.Counter()
    for commit in commits:
        feed = json.loads(git("show", f"{commit}:elections.json").decode("utf-8"))
        for records in (feed.get("months") or {}).values():
            for record in records:
                counts[str(record.get("country", ""))] += 1
    return counts, len(commits)


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("ref", help="last commit to include, e.g. ff30417")
    args = parser.parse_args(argv)
    counts, feeds = count(args.ref)
    lines = [
        f"# Country strings in the {feeds} elections.json versions up to {args.ref}.",
        "# Generated by scripts/count_feed_countries.py; do not edit.",
        "country\tcount",
        *(f"{name}\t{n}" for name, n in sorted(counts.items()) if name.strip()),
    ]
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(counts)} strings from {feeds} feeds -> {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
