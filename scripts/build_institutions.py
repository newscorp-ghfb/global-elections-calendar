"""Build data/institutions.yaml (spec §6.3).

Inputs: the IPU Parline chamber table saved in
tests/fixtures/ipu/2026-10-16/elections.html (Country, Chamber, Structure of
parliament, Chamber type, Principal mode of designation of members) and
data/institutions_manual.yaml. The output is committed and its diff reviewed.

A chamber the IPU marks "(Suspended)" or "(Dissolved)" is kept under its
plain name with that status, so its identity survives; only active chambers
must form a uni- or bicameral structure.

    .venv\\Scripts\\python.exe -m scripts.build_institutions
"""

import re
import sys
from pathlib import Path
from typing import Any

import yaml
from bs4 import BeautifulSoup

from elections_calendar.places import PlaceRegistry
from elections_calendar.text import collapse_ws

ROOT = Path(__file__).resolve().parent.parent
IPU_TABLE = ROOT / "tests" / "fixtures" / "ipu" / "2026-10-16" / "elections.html"
MANUAL = ROOT / "data" / "institutions_manual.yaml"
OUT = ROOT / "data" / "institutions.yaml"

CHAMBER_TYPES = {"lower chamber": "lower_house", "upper chamber": "upper_house"}
DESIGNATIONS = {
    "directly elected": "direct",
    "indirectly elected": "indirect",
    "appointed": "appointed",
}
_STATUS = re.compile(r"\s*\((?P<status>suspended|dissolved)\)\s*$", re.IGNORECASE)


class BuildError(Exception):
    pass


def ipu_chambers(html: str, places: PlaceRegistry) -> dict[str, list[dict[str, Any]]]:
    table = BeautifulSoup(html, "lxml").find("table")
    if table is None:
        raise BuildError("no table in the IPU page")
    rows = table.find_all("tr")
    header = [collapse_ws(c.get_text(" ")).casefold() for c in rows[0].find_all(["th", "td"])]
    col = {name: header.index(name) for name in (
        "country", "chamber", "structure of parliament", "chamber type",
        "principal mode of designation of members",
    )}  # fmt: skip
    out: dict[str, list[dict[str, Any]]] = {}
    for row in rows[1:]:
        cells = [collapse_ws(c.get_text(" ")) for c in row.find_all("td")]
        if len(cells) < len(header):
            raise BuildError(f"short IPU row: {cells}")
        name, status = cells[col["chamber"]], "active"
        marked = _STATUS.search(name)
        if marked:
            name, status = name[: marked.start()], marked["status"].casefold()
        place = places.resolve(cells[col["country"]])
        if place is None or not place.registered:
            raise BuildError(f"IPU country {cells[col['country']]!r} is not a registered place")
        unicameral = cells[col["structure of parliament"]].casefold() == "unicameral"
        chamber_type = cells[col["chamber type"]].casefold()
        office_class = "legislature" if unicameral else CHAMBER_TYPES.get(chamber_type)
        if office_class is None:
            raise BuildError(f"unknown chamber type {chamber_type!r} for {place.place_id}")
        designation = cells[col["principal mode of designation of members"]].casefold()
        out.setdefault(place.place_id, []).append(
            {
                "name": name,
                "office_class": office_class,
                "designation": DESIGNATIONS.get(designation, "other"),
                "status": status,
                "aliases": [],
            }
        )
    return out


def build(html: str, manual: dict[str, Any], places: PlaceRegistry) -> dict[str, Any]:
    chambers = ipu_chambers(html, places)
    for place_id, by_name in manual["aliases"].items():
        for name, aliases in by_name.items():
            match = [c for c in chambers.get(place_id, []) if c["name"] == name]
            if len(match) != 1:
                raise BuildError(f"{place_id} has no IPU chamber called {name!r}")
            match[0]["aliases"] = sorted(aliases)
    for place_id, extra in manual["extra"].items():
        if place_id in chambers:
            raise BuildError(f"{place_id} is already in the IPU table")
        if place_id not in places:
            raise BuildError(f"{place_id} is not a registered place")
        chambers[place_id] = [
            {
                "name": c["name"],
                "office_class": c["office_class"],
                "designation": c["designation"],
                "status": "active",
                "aliases": sorted(c.get("aliases", [])),
            }
            for c in extra
        ]
    for place_id, items in chambers.items():
        classes = sorted(c["office_class"] for c in items if c["status"] == "active")
        if classes not in ([], ["legislature"], ["lower_house", "upper_house"]):
            raise BuildError(
                f"{place_id}: active chambers {classes} are neither uni- nor bicameral"
            )
    return {place_id: chambers[place_id] for place_id in sorted(chambers)}


def render(institutions: dict[str, Any]) -> str:
    header = "# Generated by scripts/build_institutions.py from the IPU chamber table and\n"
    header += "# data/institutions_manual.yaml. Do not edit; edit the inputs and rebuild.\n"
    header += f"# Chamber status is as of the IPU capture of {IPU_TABLE.parent.name}.\n"
    return header + yaml.safe_dump(institutions, allow_unicode=True, sort_keys=False, width=100)


def main() -> int:
    manual = yaml.safe_load(MANUAL.read_text(encoding="utf-8"))
    html = IPU_TABLE.read_text(encoding="utf-8")
    institutions = build(html, manual, PlaceRegistry.load())
    OUT.write_text(render(institutions), encoding="utf-8", newline="\n")
    print(f"{len(institutions)} places with chambers -> {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
