"""Build data/subdivisions.yaml (plan 2a task 2).

Inputs: pycountry (ISO 3166-2, first-level subdivisions only) and
data/subdivisions_manual.yaml (English exonyms pycountry lacks). The output is
committed and its diff reviewed; nothing reads pycountry at runtime.

Keys per subdivision: its name without a trailing parenthesised part, and, when
the name holds ", ", the part before the first ", " ("Madrid, Comunidad de" adds
"madrid"). A key two codes of one country share is left out and listed in the
header. Manual entries are added after that check and win over generated keys.

    .venv\\Scripts\\python.exe -m scripts.build_subdivisions
"""

import re
import sys
from collections.abc import Iterable
from importlib.metadata import version
from pathlib import Path

import pycountry
import yaml

from elections_calendar.text import norm_name

ROOT = Path(__file__).resolve().parent.parent
MANUAL = ROOT / "data" / "subdivisions_manual.yaml"
OUT = ROOT / "data" / "subdivisions.yaml"

_TRAILING_PARENS = re.compile(r"\s*\([^)]*\)$")


class BuildError(Exception):
    pass


def first_level_rows() -> list[tuple[str, str, str]]:
    """(code, country_code, name) of every pycountry subdivision without a parent."""
    return [
        (sub.code, sub.country_code, sub.name)
        for sub in pycountry.subdivisions
        if sub.parent_code is None
    ]


def _keys(name: str) -> set[str]:
    base = _TRAILING_PARENS.sub("", name)
    keys = {norm_name(base)}
    if ", " in base:
        keys.add(norm_name(base.split(", ", 1)[0]))
    keys.discard("")
    return keys


def build(
    rows: Iterable[tuple[str, str, str]], manual: dict[str, dict[str, str]]
) -> tuple[dict[str, dict[str, str]], list[str]]:
    codes: set[str] = set()
    owners: dict[str, dict[str, set[str]]] = {}
    for code, country, name in rows:
        codes.add(code)
        for key in _keys(name):
            owners.setdefault(country, {}).setdefault(key, set()).add(code)
    index: dict[str, dict[str, str]] = {}
    ambiguous: list[str] = []
    for country, keyed in owners.items():
        for key, found in keyed.items():
            if len(found) == 1:
                index.setdefault(country, {})[key] = next(iter(found))
            else:
                ambiguous.append(f"{country} {key}")
    for country, names in manual.items():
        for name, code in names.items():
            if code not in codes:
                raise BuildError(f"{code} is not a first-level ISO 3166-2 code")
            if code.split("-")[0] != country:
                raise BuildError(f"{code} is listed under {country}")
            key = norm_name(name)
            if not key:
                raise BuildError(f"{country}: empty manual name {name!r}")
            index.setdefault(country, {})[key] = code
    return index, sorted(ambiguous)


def render(index: dict[str, dict[str, str]], ambiguous: list[str]) -> str:
    body = {
        country: dict(sorted(keys.items())) for country, keys in sorted(index.items())
    }
    header = "# Generated by scripts/build_subdivisions.py from pycountry "
    header += f"{version('pycountry')} and\n"
    header += "# data/subdivisions_manual.yaml. Do not edit; edit the inputs and rebuild.\n"
    header += f"# Left out as ambiguous ({len(ambiguous)}): {', '.join(ambiguous)}\n"
    return header + yaml.safe_dump(body, allow_unicode=True, sort_keys=False, width=100)


def main() -> int:
    manual = yaml.safe_load(MANUAL.read_text(encoding="utf-8"))
    index, ambiguous = build(first_level_rows(), manual)
    OUT.write_text(render(index, ambiguous), encoding="utf-8", newline="\n")
    keys = sum(len(v) for v in index.values())
    summary = f"{len(index)} countries, {keys} keys, {len(ambiguous)} ambiguous"
    print(f"{summary} -> {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
